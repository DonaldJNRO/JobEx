// Regenerates src/lib/region-currency.ts from CLDR.
//
// WHY GENERATED. The table was hand-written and had 18 regions on the web and
// 32 in the mobile app, so the two already disagreed: a guest in Brazil saw
// BRL on the phone and ₦ on the website. Mexico, India, Japan, the UAE,
// Egypt, China, Turkey and Saudi Arabia were in neither, so those visitors
// got no conversion at all.
//
// Nobody is going to hand-maintain 255 rows correctly, so this reads the
// authoritative source instead: Unicode CLDR's supplemental currencyData,
// the same data the Intl built-ins are generated from.
//
// A REGION IS ONLY INCLUDED IF THE RATE FEED CARRIES ITS CURRENCY. Mapping a
// visitor to a currency we cannot convert into is worse than not mapping
// them: buildDisplayPrice would have a target and no rate. Today that drops
// nothing, but a future CLDR release could add one.
//
//   node scripts/gen-region-currency.mjs
//
// Run it when CLDR publishes a currency change, which is rare: a country
// redenominating or adopting another country's money.

import { writeFileSync } from "node:fs";

const CLDR = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/supplemental/currencyData.json";
const RATES = "https://cdn.jsdelivr.net/npm/@fawazahmed0/currency-api@latest/v1/currencies/gbp.json";

const [cldr, rates] = await Promise.all(
  [CLDR, RATES].map((u) => fetch(u).then((r) => {
    if (!r.ok) throw new Error(`${u}: HTTP ${r.status}`);
    return r.json();
  })),
);

const have = new Set(Object.keys(rates.gbp).map((c) => c.toUpperCase()));
const out = {};
for (const [region, entries] of Object.entries(cldr.supplemental.currencyData.region)) {
  if (!/^[A-Z]{2}$/.test(region)) continue;
  let current = null;
  for (const e of entries) {
    for (const [code, meta] of Object.entries(e)) {
      if (meta._to) continue;             // withdrawn
      if (meta._tender === "false") continue; // not legal tender, e.g. MXV
      current = code;
    }
  }
  if (current && have.has(current)) out[region] = current;
}

const rows = Object.keys(out).sort().map((k) => `  ${k}: "${out[k]}",`).join("\n");
writeFileSync(new URL("../src/lib/region-currency.ts", import.meta.url),
`// GENERATED by scripts/gen-region-currency.mjs from Unicode CLDR. Do not edit.
//
// ISO 3166 region to the currency people there actually spend, used to show a
// visitor a price in their own money rather than the operator's. Every entry
// is current legal tender AND carried by the exchange rate feed, so a region
// listed here can always be converted into.
//
// Generated ${new Date().toISOString().slice(0, 10)} from ${Object.keys(out).length} regions.

export const REGION_CURRENCY: Record<string, string> = {
${rows}
};
`);
console.log(`wrote ${Object.keys(out).length} regions`);
